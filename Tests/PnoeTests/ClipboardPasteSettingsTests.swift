import AppKit
import XCTest

/// The clipboard settings of pasting: the default restore delay, the transient marker with and without clipboard
/// history, and the restore that stands down when the clipboard changed. Every pasteboard here is a private named
/// one; nothing touches the general pasteboard.
final class ClipboardPasteSettingsTests: XCTestCase {
    private func makeDefaults() -> UserDefaults {
        let name = "ClipboardPasteSettingsTests.\(UUID().uuidString)"
        let defaults = UserDefaults(suiteName: name)!
        addTeardownBlock { defaults.removePersistentDomain(forName: name) }
        return defaults
    }

    private func makePasteboard() -> NSPasteboard {
        let pasteboard = NSPasteboard(name: NSPasteboard.Name("com.techneissa.pnoe.tests.\(UUID().uuidString)"))
        addTeardownBlock { pasteboard.releaseGlobally() }
        return pasteboard
    }

    private func writeDictation(
        _ text: String = "dictated words",
        transient: Bool,
        sessionID: String? = "session-1",
        on pasteboard: NSPasteboard
    ) -> Bool {
        PasteClipboard.write(
            text, transient: transient, sessionID: sessionID, on: pasteboard, sourceBundleIdentifier: "test.pnoe")
    }

    // MARK: - Defaults

    func testFreshInstallRestoresAfterHalfASecondAndAddsToHistory() {
        let defaults = makeDefaults()
        defaults.register(defaults: ClipboardPasteSettings.registeredDefaults)

        XCTAssertEqual(defaults.double(forKey: ClipboardPasteSettings.delayKey), 0.5)
        XCTAssertEqual(ClipboardPasteSettings.restoreDelay(defaults: defaults), 0.5)
        XCTAssertTrue(ClipboardPasteSettings.restoresClipboard(defaults: defaults))
        XCTAssertTrue(ClipboardPasteSettings.addsToHistory(defaults: defaults))
    }

    func testMissingValuesReadAsTheDefaults() {
        let defaults = makeDefaults()
        XCTAssertEqual(ClipboardPasteSettings.restoreDelay(defaults: defaults), 0.5)
        XCTAssertTrue(ClipboardPasteSettings.addsToHistory(defaults: defaults))
    }

    func testExplicitChoicesSurviveRegisteringTheDefaults() {
        let defaults = makeDefaults()
        defaults.set(2.0, forKey: ClipboardPasteSettings.delayKey)
        defaults.set(false, forKey: ClipboardPasteSettings.restoreKey)
        defaults.set(false, forKey: ClipboardPasteSettings.addToHistoryKey)
        defaults.register(defaults: ClipboardPasteSettings.registeredDefaults)

        XCTAssertEqual(ClipboardPasteSettings.restoreDelay(defaults: defaults), 2.0)
        XCTAssertFalse(ClipboardPasteSettings.restoresClipboard(defaults: defaults))
        XCTAssertFalse(ClipboardPasteSettings.addsToHistory(defaults: defaults))
    }

    func testAnExplicitShortOrLongDelayIsKeptWithinTheLimits() {
        let defaults = makeDefaults()
        defaults.set(0.25, forKey: ClipboardPasteSettings.delayKey)
        XCTAssertEqual(ClipboardPasteSettings.restoreDelay(defaults: defaults), 0.25)
        defaults.set(0.05, forKey: ClipboardPasteSettings.delayKey)
        XCTAssertEqual(ClipboardPasteSettings.restoreDelay(defaults: defaults), ClipboardPasteSettings.minimumRestoreDelay)
        defaults.set(30.0, forKey: ClipboardPasteSettings.delayKey)
        XCTAssertEqual(ClipboardPasteSettings.restoreDelay(defaults: defaults), ClipboardPasteSettings.maximumRestoreDelay)
    }

    func testTheDefaultIsOneOfThePickerOptions() {
        XCTAssertTrue(ClipboardPasteSettings.restoreDelayOptions.contains(ClipboardPasteSettings.defaultRestoreDelay))
        XCTAssertGreaterThanOrEqual(ClipboardPasteSettings.defaultRestoreDelay, ClipboardPasteSettings.minimumRestoreDelay)
    }

    // MARK: - Transient marker

    func testMarkerOnlyWhileRestoringWithHistoryOff() {
        XCTAssertTrue(ClipboardPasteSettings.marksDictationTransient(restoring: true, addToHistory: false))
        XCTAssertFalse(ClipboardPasteSettings.marksDictationTransient(restoring: true, addToHistory: true))
        XCTAssertFalse(ClipboardPasteSettings.marksDictationTransient(restoring: false, addToHistory: false))
        XCTAssertFalse(ClipboardPasteSettings.marksDictationTransient(restoring: false, addToHistory: true))
    }

    func testDictationWithoutTheMarkerCanBeRecordedByHistoryApps() throws {
        let pasteboard = makePasteboard()
        XCTAssertTrue(writeDictation(transient: false, on: pasteboard))

        let types = try XCTUnwrap(pasteboard.types)
        XCTAssertFalse(types.contains(PasteClipboard.transientType))
        XCTAssertFalse(types.contains(PasteClipboard.autoGeneratedType))
        XCTAssertEqual(pasteboard.string(forType: .string), "dictated words")
    }

    func testDictationWithTheMarkerIsSkippedByHistoryApps() throws {
        let pasteboard = makePasteboard()
        XCTAssertTrue(writeDictation(transient: true, on: pasteboard))

        let types = try XCTUnwrap(pasteboard.types)
        XCTAssertTrue(types.contains(PasteClipboard.transientType))
        XCTAssertTrue(types.contains(PasteClipboard.autoGeneratedType))
        XCTAssertEqual(pasteboard.string(forType: .string), "dictated words")
    }

    // MARK: - Restore

    private func seed(_ pasteboard: NSPasteboard, text: String) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data([1, 2, 3]), forType: NSPasteboard.PasteboardType("test.custom"))
        pasteboard.writeObjects([item])
    }

    func testRestorePutsTheEarlierItemBack() {
        let pasteboard = makePasteboard()
        seed(pasteboard, text: "copied before")
        let saved = PasteClipboard.snapshot(of: pasteboard)

        XCTAssertTrue(writeDictation(transient: false, on: pasteboard))
        let outcome = PasteClipboard.restore(
            saved, expectedText: "dictated words", sessionID: "session-1", on: pasteboard)

        XCTAssertEqual(outcome, .restored)
        XCTAssertEqual(pasteboard.string(forType: .string), "copied before")
        XCTAssertEqual(
            pasteboard.data(forType: NSPasteboard.PasteboardType("test.custom")), Data([1, 2, 3]))
        XCTAssertNil(pasteboard.string(forType: PasteClipboard.pasteSessionType))
    }

    func testRestoreIsSkippedWhenTheUserCopiedSomethingElse() {
        let pasteboard = makePasteboard()
        seed(pasteboard, text: "copied before")
        let saved = PasteClipboard.snapshot(of: pasteboard)
        XCTAssertTrue(writeDictation(transient: false, on: pasteboard))

        pasteboard.clearContents()
        pasteboard.setString("copied meanwhile", forType: .string)
        let outcome = PasteClipboard.restore(
            saved, expectedText: "dictated words", sessionID: "session-1", on: pasteboard)

        XCTAssertEqual(outcome, .skippedClipboardChanged)
        XCTAssertEqual(pasteboard.string(forType: .string), "copied meanwhile")
    }

    func testRestoreIsSkippedWhenTheSameTextWasCopiedAgainOutsideThePaste() {
        let pasteboard = makePasteboard()
        seed(pasteboard, text: "copied before")
        let saved = PasteClipboard.snapshot(of: pasteboard)
        XCTAssertTrue(writeDictation(transient: false, on: pasteboard))

        pasteboard.clearContents()
        pasteboard.setString("dictated words", forType: .string)
        let outcome = PasteClipboard.restore(
            saved, expectedText: "dictated words", sessionID: "session-1", on: pasteboard)

        XCTAssertEqual(outcome, .skippedClipboardChanged)
        XCTAssertEqual(pasteboard.string(forType: .string), "dictated words")
    }

    func testRestoreIsSkippedForAnotherPasteSession() {
        let pasteboard = makePasteboard()
        seed(pasteboard, text: "copied before")
        let saved = PasteClipboard.snapshot(of: pasteboard)
        XCTAssertTrue(writeDictation(transient: false, sessionID: "session-2", on: pasteboard))

        let outcome = PasteClipboard.restore(
            saved, expectedText: "dictated words", sessionID: "session-1", on: pasteboard)

        XCTAssertEqual(outcome, .skippedClipboardChanged)
        XCTAssertEqual(pasteboard.string(forType: .string), "dictated words")
    }

    func testRestoreWithAnEmptyClipboardBeforeLeavesItEmpty() {
        let pasteboard = makePasteboard()
        pasteboard.clearContents()
        let saved = PasteClipboard.snapshot(of: pasteboard)
        XCTAssertTrue(saved.isEmpty)
        XCTAssertTrue(writeDictation(transient: false, on: pasteboard))

        let outcome = PasteClipboard.restore(
            saved, expectedText: "dictated words", sessionID: "session-1", on: pasteboard)

        XCTAssertEqual(outcome, .restored)
        XCTAssertNil(pasteboard.string(forType: .string))
    }
}
