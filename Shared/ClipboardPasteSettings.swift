import AppKit
import Foundation

/// The settings behind "After pasting": whether the dictated text stays on the clipboard or what was copied before
/// is put back, how long Pnoe waits before putting it back, and whether clipboard history apps may record the
/// dictated text. Keys, defaults and the delay clamp live here so the paste code, the settings screen, the backup and
/// the tests read one source.
enum ClipboardPasteSettings {
    /// On: put back the previous clipboard after pasting. Off: the dictated text stays.
    static let restoreKey = "restoreClipboardAfterPaste"
    static let delayKey = "clipboardRestoreDelay"
    /// While the previous clipboard is put back: let clipboard history apps record the dictated text.
    static let addToHistoryKey = "addDictatedTextToClipboardHistory"

    static let defaultRestoreDelay: TimeInterval = 0.5
    /// The shortest wait after the paste command is posted. The command is posted before the wait starts; this keeps
    /// the old clipboard from returning before the target app has read the dictated text.
    static let minimumRestoreDelay: TimeInterval = 0.25
    static let maximumRestoreDelay: TimeInterval = 5.0
    static let restoreDelayOptions: [TimeInterval] = [0.25, 0.5, 1, 2, 3, 4, 5]

    /// What a fresh install gets; the app registers it at launch, so a value the user saved is never replaced.
    static let registeredDefaults: [String: Any] = [
        restoreKey: true,
        delayKey: defaultRestoreDelay,
        addToHistoryKey: true,
    ]

    /// The wait before the previous clipboard comes back. A missing value is the default; a saved one is clamped.
    static func restoreDelay(defaults: UserDefaults = .standard) -> TimeInterval {
        guard defaults.object(forKey: delayKey) != nil else { return defaultRestoreDelay }
        return min(max(defaults.double(forKey: delayKey), minimumRestoreDelay), maximumRestoreDelay)
    }

    static func restoresClipboard(defaults: UserDefaults = .standard) -> Bool {
        defaults.bool(forKey: restoreKey)
    }

    static func addsToHistory(defaults: UserDefaults = .standard) -> Bool {
        defaults.object(forKey: addToHistoryKey) == nil ? true : defaults.bool(forKey: addToHistoryKey)
    }

    /// Whether the dictated text is marked so clipboard history apps skip it: only while the old clipboard is put
    /// back and the history toggle is off.
    static func marksDictationTransient(restoring: Bool, addToHistory: Bool) -> Bool {
        restoring && !addToHistory
    }
}

/// Writing the dictated text to a pasteboard and putting the previous contents back. Takes the pasteboard as an
/// argument so tests use a private named one and never the general pasteboard.
enum PasteClipboard {
    typealias ItemSnapshot = [(NSPasteboard.PasteboardType, Data)]
    typealias Snapshot = [ItemSnapshot]

    static let pasteSessionType = NSPasteboard.PasteboardType("com.Pnoe.PasteSession")
    static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    enum RestoreOutcome: Equatable {
        case restored
        /// The clipboard changed since the paste (the user copied something): nothing is touched.
        case skippedClipboardChanged
        case failed
    }

    static func write(
        _ text: String,
        transient: Bool,
        sessionID: String?,
        on pasteboard: NSPasteboard,
        sourceBundleIdentifier: String? = Bundle.main.bundleIdentifier
    ) -> Bool {
        pasteboard.clearContents()
        guard pasteboard.setString(text, forType: .string) else { return false }

        if let sourceBundleIdentifier {
            pasteboard.setString(sourceBundleIdentifier, forType: sourceType)
        }

        if transient {
            pasteboard.setData(Data(), forType: transientType)
            pasteboard.setData(Data(), forType: autoGeneratedType)
        }

        if let sessionID, !pasteboard.setString(sessionID, forType: pasteSessionType) {
            return false
        }

        return pasteboard.string(forType: .string) == text
    }

    static func snapshot(of pasteboard: NSPasteboard) -> Snapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in
                item.data(forType: type).map { (type, $0) }
            }
        }
    }

    /// Puts `snapshot` back, but only while the pasteboard still holds this paste session's text.
    static func restore(
        _ snapshot: Snapshot,
        expectedText: String,
        sessionID: String,
        on pasteboard: NSPasteboard
    ) -> RestoreOutcome {
        guard
            pasteboard.string(forType: .string) == expectedText,
            pasteboard.string(forType: pasteSessionType) == sessionID
        else { return .skippedClipboardChanged }

        pasteboard.clearContents()
        if !snapshot.isEmpty, !pasteboard.writeObjects(items(from: snapshot)) { return .failed }
        return .restored
    }

    private static func items(from snapshot: Snapshot) -> [NSPasteboardItem] {
        snapshot.map { itemSnapshot in
            let item = NSPasteboardItem()
            for (type, data) in itemSnapshot {
                item.setData(data, forType: type)
            }
            return item
        }
    }
}
