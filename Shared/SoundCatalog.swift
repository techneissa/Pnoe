import Foundation

/// A moment in the app that can make a sound.
enum SoundEvent: String, CaseIterable, Identifiable {
    case start
    case stop
    case cancel
    case error

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .start: String(localized: "Start Sound")
        case .stop: String(localized: "Stop Sound")
        case .cancel: String(localized: "Cancel Sound")
        case .error: String(localized: "Error Sound")
        }
    }

    var defaultChoice: SoundChoice {
        switch self {
        case .start: .pnoe(.kalimba)
        case .stop: .pnoe(.feltPiano)
        case .cancel: .pnoe(.wood)
        case .error: .pnoe(.glass)
        }
    }

    var choiceKey: String { "soundChoice.\(rawValue)" }
    var customFilenameKey: String { "custom\(rawValue.capitalized)SoundFilename" }
    var customStandardName: String { "Custom\(rawValue.capitalized)Sound" }
}

/// One of Pnoe's own sound sets. Each set has a sound for every event, generated by the scripts in `design/sounds`.
enum PnoeSoundSet: String, CaseIterable, Identifiable {
    case feltPiano = "felt-piano"
    case kalimba
    case vibes
    case harp
    case bloop
    case drop
    case wood
    case glass
    case sine

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .feltPiano: String(localized: "Felt Piano")
        case .kalimba: String(localized: "Kalimba")
        case .vibes: String(localized: "Vibes")
        case .harp: String(localized: "Harp")
        case .bloop: String(localized: "Bloop")
        case .drop: String(localized: "Drop")
        case .wood: String(localized: "Wood")
        case .glass: String(localized: "Glass")
        case .sine: String(localized: "Sine")
        }
    }

    /// Bundle resource name, for example `kalimba-start`.
    func resourceName(for event: SoundEvent) -> String {
        "\(rawValue)-\(event.rawValue)"
    }

    func url(for event: SoundEvent, in bundle: Bundle = .main) -> URL? {
        let name = resourceName(for: event)
        return bundle.url(forResource: name, withExtension: "wav")
            ?? bundle.url(forResource: name, withExtension: "wav", subdirectory: "Sounds")
    }
}

/// What plays for one event.
enum SoundChoice: Hashable {
    case none
    case pnoe(PnoeSoundSet)
    /// A sound macOS ships in `/System/Library/Sounds`, played by name. Never copied into the app.
    case system(String)
    /// The audio file the user imported for this event.
    case custom

    var storageValue: String {
        switch self {
        case .none: "none"
        case .pnoe(let set): "pnoe:\(set.rawValue)"
        case .system(let name): "system:\(name)"
        case .custom: "custom"
        }
    }

    init?(storageValue: String) {
        switch storageValue {
        case "none":
            self = .none
        case "custom":
            self = .custom
        case _ where storageValue.hasPrefix("pnoe:"):
            guard let set = PnoeSoundSet(rawValue: String(storageValue.dropFirst("pnoe:".count))) else { return nil }
            self = .pnoe(set)
        case _ where storageValue.hasPrefix("system:"):
            let name = String(storageValue.dropFirst("system:".count))
            guard !name.isEmpty else { return nil }
            self = .system(name)
        default:
            return nil
        }
    }
}

/// The alert sounds macOS ships. They are listed from disk at runtime and played with `NSSound(named:)`.
enum SystemSounds {
    static let directory = URL(fileURLWithPath: "/System/Library/Sounds", isDirectory: true)
    private static let audioExtensions: Set<String> = ["aiff", "aif", "wav", "caf"]

    /// Names (without extension) of the sounds that exist in `directory`, sorted. Empty when the folder is missing.
    static func available(in directory: URL = directory, fileManager: FileManager = .default) -> [String] {
        guard let files = try? fileManager.contentsOfDirectory(atPath: directory.path) else { return [] }
        let names = files.compactMap { file -> String? in
            let url = URL(fileURLWithPath: file)
            guard audioExtensions.contains(url.pathExtension.lowercased()) else { return nil }
            return url.deletingPathExtension().lastPathComponent
        }
        return names.sorted { $0.localizedStandardCompare($1) == .orderedAscending }
    }

    /// The picker label. A macOS sound that shares a name with a Pnoe set (Glass) says where it comes from.
    static func displayName(for name: String) -> String {
        PnoeSoundSet.allCases.contains { $0.displayName == name }
            ? String(format: String(localized: "%@ (macOS)"), name)
            : name
    }
}
